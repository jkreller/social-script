"""Translation catalog for framework-fixed strings. The English literal already in
the code is the lookup key — nothing needs duplicating here except the translation."""

_locale = "en"


def set_locale(locale: str) -> None:
    global _locale
    _locale = locale if locale in TRANSLATIONS else "en"


def get_locale() -> str:
    return _locale


def _(text, **kwargs):
    if not text:
        return text
    translated = TRANSLATIONS.get(_locale, {}).get(text, text)
    return translated.format(**kwargs) if kwargs else translated


